#!/usr/bin/env node
// Generates sw-manifest.js: the precache list + a content-hash VERSION for sw.js.
//   node scripts/build-sw-manifest.mjs           write sw-manifest.js
//   node scripts/build-sw-manifest.mjs --check   only verify it is current and consistent (exit 1 if not)
// Precached: index.html, manifest.webmanifest, root favicon.*, css/**, js/**, icons/** (images), assets/**.
// Never precached: sw.js, sw-manifest.js, 404.html, docs/, qa/, tests/, scripts/, dotfiles, *.md, *.mjs.

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const WEB_EXT = new Set(['.html', '.css', '.js', '.json', '.webmanifest', '.svg', '.png', '.jpg', '.jpeg', '.webp', '.gif', '.ico', '.woff2', '.woff', '.ttf', '.otf', '.txt', '.mp3', '.wav']);
const DIRS = ['css', 'js', 'icons', 'assets'];
const ROOT_FILES = [/^index\.html$/, /^manifest\.webmanifest$/, /^favicon\.[a-z0-9]+$/];
const MAX_FILE = 3 * 1024 * 1024;
const MAX_TOTAL = 20 * 1024 * 1024;

function walk(dir, rel, out) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    if (ent.name.startsWith('.')) continue;
    const r = rel ? `${rel}/${ent.name}` : ent.name;
    if (ent.isDirectory()) walk(path.join(dir, ent.name), r, out);
    else if (ent.isFile()) out.push(r);
  }
}

export function collectFiles(root = ROOT) {
  const all = [];
  for (const ent of fs.readdirSync(root, { withFileTypes: true })) {
    if (ent.isFile() && ROOT_FILES.some((re) => re.test(ent.name))) all.push(ent.name);
  }
  for (const d of DIRS) {
    const p = path.join(root, d);
    if (fs.existsSync(p) && fs.statSync(p).isDirectory()) walk(p, d, all);
  }
  return all
    .filter((f) => WEB_EXT.has(path.extname(f).toLowerCase()) && !/\.test\.js$/.test(f) && path.basename(f) !== 'package.json')
    .sort();
}

export function buildManifest(root = ROOT) {
  const files = collectFiles(root);
  const h = crypto.createHash('sha256');
  let total = 0;
  const warnings = [];
  for (const f of files) {
    const buf = fs.readFileSync(path.join(root, f));
    total += buf.length;
    if (buf.length > MAX_FILE) warnings.push(`${f} is ${(buf.length / 1048576).toFixed(1)} MB; it is precached on every device`);
    h.update(f + '\0' + crypto.createHash('sha256').update(buf).digest('hex') + '\n');
  }
  if (total > MAX_TOTAL) warnings.push(`Precache is ${(total / 1048576).toFixed(1)} MB in total (over ${MAX_TOTAL / 1048576} MB)`);
  const version = h.digest('hex').slice(0, 12);
  const text =
    '// GENERATED by scripts/build-sw-manifest.mjs. Do not edit by hand; run the script after changing shell files.\n' +
    `self.__DAYBEAT_PRECACHE = ${JSON.stringify({ version, files })};\n`;
  return { version, files, text, total, warnings };
}

const IMPORT_RE = /(?:^|[^\w$.])(?:import|export)\s*(?:[\w$*{}\s,]*?\s*from\s*)?(['"])([^'"\n]+)\1|(?:^|[^\w$.])import\(\s*(['"])([^'"\n]+)\3\s*\)/gm;

/** Problems: relative imports that do not exist, are not precached, or absolute (root-relative / URL) imports. */
export function checkImports(root, files) {
  const problems = [];
  const set = new Set(files);
  for (const f of files.filter((x) => x.endsWith('.js'))) {
    const src = fs.readFileSync(path.join(root, f), 'utf8');
    for (const m of src.matchAll(IMPORT_RE)) {
      const spec = m[2] ?? m[4];
      if (!spec) continue;
      if (spec.startsWith('/') || /^[a-z][a-z0-9+.-]*:/i.test(spec)) {
        problems.push(`${f}: absolute import "${spec}" (use a relative path)`);
        continue;
      }
      if (!spec.startsWith('./') && !spec.startsWith('../')) continue;
      const target = path.posix.normalize(path.posix.join(path.posix.dirname(f), spec.split(/[?#]/)[0]));
      if (!fs.existsSync(path.join(root, target))) problems.push(`${f}: imports "${spec}" which does not exist`);
      else if (!set.has(target)) problems.push(`${f}: imports "${spec}" which is not in the precache list`);
    }
  }
  return problems;
}

export function manifestFileCurrent(root = ROOT) {
  const { text } = buildManifest(root);
  const p = path.join(root, 'sw-manifest.js');
  return fs.existsSync(p) && fs.readFileSync(p, 'utf8') === text;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes('--check');
  const m = buildManifest(ROOT);
  const problems = checkImports(ROOT, m.files);
  for (const w of m.warnings) console.error(`warning: ${w}`);
  for (const p of problems) console.error(`problem: ${p}`);
  const file = path.join(ROOT, 'sw-manifest.js');
  const current = fs.existsSync(file) && fs.readFileSync(file, 'utf8') === m.text;
  if (check) {
    if (!current) console.error('sw-manifest.js is stale or missing. Run: node scripts/build-sw-manifest.mjs');
    else console.log(`sw-manifest.js is current (version ${m.version}, ${m.files.length} files)`);
    process.exit(current && problems.length === 0 ? 0 : 1);
  }
  fs.writeFileSync(file, m.text);
  console.log(`wrote sw-manifest.js: version ${m.version}, ${m.files.length} files, ${(m.total / 1024).toFixed(0)} KB`);
  process.exit(problems.length ? 1 : 0);
}
